-- The bookkeeping schema, version 1 (README "Target schema"). Run once by `init`, in one transaction.
CREATE SCHEMA _rowvioli;

CREATE TABLE _rowvioli.sources (
    id               int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             text NOT NULL UNIQUE,
    type             text NOT NULL,
    target_schema    text,
    parallel         int NOT NULL DEFAULT 2,
    max_delete_share numeric NOT NULL DEFAULT 0.5,
    max_seconds      int NOT NULL DEFAULT 3600,
    options          jsonb NOT NULL DEFAULT '{}',
    connection       bytea,
    key_id           text,
    enabled          boolean NOT NULL DEFAULT true);

CREATE TABLE _rowvioli.tables (
    id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source       text NOT NULL REFERENCES _rowvioli.sources (name),
    source_table text NOT NULL,
    target_table text NOT NULL,
    key          text[],
    max_age      interval NOT NULL,
    log          boolean NOT NULL DEFAULT true,
    options      jsonb NOT NULL DEFAULT '{}',
    enabled      boolean NOT NULL DEFAULT true,
    loaded_at    timestamptz,
    attempted_at timestamptz,
    attempts     int NOT NULL DEFAULT 0,
    requested_at timestamptz,
    reason       text,
    UNIQUE (source, source_table));

CREATE TABLE _rowvioli.runs (
    run         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "table"     int NOT NULL REFERENCES _rowvioli.tables (id),
    worker      text NOT NULL,
    started_at  timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    status      text NOT NULL DEFAULT 'running',
    rows_read   bigint,
    inserted    bigint,
    updated     bigint,
    deleted     bigint,
    reason      text,
    definition  text);

CREATE TABLE _rowvioli.meta (
    schema_version int NOT NULL,
    max_running    int NOT NULL DEFAULT 20,
    definition     text);

INSERT INTO _rowvioli.meta (schema_version) VALUES (1);

CREATE VIEW _rowvioli.status AS
SELECT t.id, s.id AS source_id, t.source, t.source_table,
       s.target_schema || '.' || t.target_table AS target_table,
       t.max_age, t.loaded_at, now() - t.loaded_at AS age, d.due_at, st.status, t.attempts,
       CASE WHEN st.status = 'failed' THEN coalesce(t.reason, 'worker lost') ELSE t.reason END AS reason,
       t.attempted_at, t.requested_at
  FROM _rowvioli.tables t
  JOIN _rowvioli.sources s ON s.name = t.source
 CROSS JOIN LATERAL (SELECT CASE
         WHEN t.attempted_at IS NULL THEN now()
         WHEN t.requested_at > t.attempted_at THEN t.requested_at
         WHEN t.attempts = 0 THEN t.loaded_at + t.max_age
         -- the pause: one minute, doubled per further attempt, never longer than max_age
         ELSE t.attempted_at + least(interval '1 minute' * power(2, least(t.attempts - 1, 30)), t.max_age)
       END AS due_at) d
 CROSS JOIN LATERAL (SELECT CASE
         -- loading means: somebody holds the table lock (source id, table id) in this database
         WHEN EXISTS (SELECT FROM pg_locks l
                       WHERE l.locktype = 'advisory' AND l.objsubid = 2 AND l.granted
                         AND l.database = (SELECT oid FROM pg_database WHERE datname = current_database())
                         AND l.classid = s.id::oid AND l.objid = t.id::oid) THEN 'loading'
         WHEN t.attempted_at IS NULL THEN 'new'
         WHEN t.attempts = 0 THEN 'ok'
         ELSE 'failed'
       END AS status) st
 WHERE t.enabled AND s.enabled;
